"""Generate help for CLI flags backed directly by OpenAPI request fields."""

import json
from pathlib import Path
import sys

import yaml

from openapi_schema import resolve_ref


def product_duration_help(spec):
    operation = spec["paths"]["/projects/{project_id}/products"]["post"]
    body = resolve_ref(operation["requestBody"], spec)
    schema = resolve_ref(body["content"]["application/json"]["schema"], spec)
    subscription = resolve_ref(schema["properties"]["subscription"], spec)
    field = subscription["properties"]["duration"]
    duration = resolve_ref(field, spec)
    # The shared Duration schema describes other uses such as product reads.
    description = field["description"]
    values = ", ".join(duration["enum"])
    return f"{description} Allowed values: {values}."


def main():
    spec_path, output_path = map(Path, sys.argv[1:])
    spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
    help_text = json.dumps(product_duration_help(spec), ensure_ascii=False)
    output_path.write_text(
        "// Code generated by scripts/gen-command-help.py. DO NOT EDIT.\n\n"
        "package cli\n\n"
        f"const productCreateDurationHelp = {help_text}\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
